<?php

namespace Camaleaun\Eject;

use WP_CLI;
use WP_CLI\Utils;

/**
 * The project repository's own files: .gitignore (a whitelist: only the
 * blueprint, the deploy files and the site's own code are committed) and
 * .editorconfig (WordPress coding standards).
 */
class Repository {

	/*
	 * TODO: .gitignore and .editorconfig carry no "generated" text on purpose (nothing a developer
	 * reads in them says where they came from). Pipeline::is_generated() recognizes them by their
	 * content instead; a marker or a credit would be an option there.
	 */

	const EDITORCONFIG = <<<'EDITORCONFIG'
# This file is for unifying the coding style for different editors and IDEs
# editorconfig.org

# WordPress Coding Standards
# https://make.wordpress.org/core/handbook/coding-standards/

root = true

[*]
charset = utf-8
end_of_line = lf
insert_final_newline = true
trim_trailing_whitespace = true
indent_style = tab

[*.yml]
indent_style = space
indent_size = 2

[*.md]
trim_trailing_whitespace = false

EDITORCONFIG;

	/**
	 * @param string[]    $code    Paths (relative to the root) of the site's own code: files or directories.
	 * @param string|null $ci_file The provider's CI file, or null without CI.
	 * @param callable    $is_dir  Tells whether a relative path is a directory.
	 * @param array       $info    Data for README.md (see Command::readme_info()); none: no README.md.
	 * @return array<string,string> Relative path => content.
	 */
	public static function files( array $code, $ci_file, callable $is_dir, array $info = array(), array $ignore = array() ) {
		$files = array(
			'.gitignore'    => self::gitignore( $code, $ci_file, $is_dir, $ignore ),
			'.editorconfig' => self::EDITORCONFIG,
		);
		if ( $info ) {
			$files['README.md'] = Utils\mustache_render( dirname( __DIR__ ) . '/templates/readme-md.mustache', $info );
		}
		return $files;
	}

	/**
	 * Writes the files into the site (--no-bundle). An existing file that was not
	 * generated by wp eject is left alone unless $overwrite.
	 *
	 * @param array<string,string> $files
	 * @return array<string,string> Relative path => "written" | "kept (…)".
	 */
	public static function write( Site $site, array $files, $overwrite ) {
		$result = array();
		foreach ( $files as $path => $content ) {
			$file  = $site->root . $path;
			$state = 'written';
			if ( is_file( $file ) && ! $overwrite && ! Pipeline::is_generated( $file ) ) {
				$blocker = Git::overwrite_blocker( $site->root, $path );
				if ( '' !== $blocker ) {
					WP_CLI::warning( "{$path} exists and was not generated by wp eject, and {$blocker}: left as is (use --overwrite-ci to replace it)." );
					$result[ $path ] = 'kept (exists, not generated by wp eject)';
					continue;
				}
				$state = 'written (replaced: git has the previous version)';
			}
			file_put_contents( $file, $content );
			$result[ $path ] = $state;
		}
		return $result;
	}

	/**
	 * A whitelist: ignore everything, then release the repository files and each
	 * piece of the site's own code (and every folder above it, re-ignoring the
	 * rest of that folder).
	 *
	 * @param string[]    $code
	 * @param string|null $ci_file
	 */
	private static function gitignore( array $code, $ci_file, callable $is_dir, array $ignore = array() ) {
		$lines = array(
			'# System',
			'.DS_Store',
			'*.swp',
			'',
			'# Root',
			'/*',
			'!/.gitignore',
			'!/.editorconfig',
			'!/README.md',
			'!/blueprint.json',
		);
		if ( null !== $ci_file ) {
			$lines[] = '!/deploy/';
			$lines[] = 0 === strpos( $ci_file, '.github/' ) ? '!/.github/' : '!/' . $ci_file;
		}

		$lines[] = '';
		$lines[] = "# The site's own code";
		if ( ! $code ) {
			$lines[] = '# (none: everything in wp-content comes from the blueprint). To add some, e.g.';
			$lines[] = '# a custom plugin and a child theme (its parent theme comes from the blueprint):';
			$lines[] = '#   !/wp-content/';
			$lines[] = '#   /wp-content/*';
			$lines[] = '#   !/wp-content/plugins/';
			$lines[] = '#   /wp-content/plugins/*';
			$lines[] = '#   !/wp-content/plugins/acme-core/';
			$lines[] = '#   !/wp-content/themes/';
			$lines[] = '#   /wp-content/themes/*';
			$lines[] = '#   !/wp-content/themes/acme-child/';
			$lines[] = '# A line like these is added for each custom plugin or theme.';
		}

		sort( $code );
		$released = array();
		foreach ( array_unique( $code ) as $path ) {
			$parts = explode( '/', trim( $path, '/' ) );
			$last  = count( $parts ) - 1;
			$dir   = '';
			for ( $i = 0; $i < $last; $i++ ) {
				$dir .= ( '' === $dir ? '' : '/' ) . $parts[ $i ];
				if ( ! isset( $released[ $dir ] ) ) {
					$released[ $dir ] = true;
					$lines[]          = '!/' . $dir . '/';
					$lines[]          = '/' . $dir . '/*';
				}
			}
			$lines[] = '!/' . trim( $path, '/' ) . ( $is_dir( $path ) ? '/' : '' );
		}

		if ( $ignore ) {
			// After the whitelist: the last matching rule wins.
			sort( $ignore );
			$lines[] = '';
			$lines[] = '# Temporary files of an interrupted transfer: never committed';
			foreach ( $ignore as $path ) {
				$lines[] = '/' . ltrim( $path, '/' );
			}
		}

		return implode( "\n", $lines ) . "\n";
	}
}
